# Below this many unlocked characters, practice serves individual characters
# instead of sentences (see JuziEngine.pick_hsk_sentences) -- a deliberate
# beginner phase paired with seed_brain.py's Tier 1 ("First Peel"), which
# now picks characters for simplicity rather than sentence coverage and so
# usually unlocks zero playable sentences on purpose. Once a learner has
# enough characters that real sentences become possible regardless of how
# they got there (seeding, Paste Text, Suggest Characters), practice
# transitions to sentences automatically -- this is a running character
# count, not a one-time tier choice.
CHARACTER_ONLY_UNLOCK_THRESHOLD = 20

# Stand-in stroke count for a character missing one in master_dictionary.json
# (a small handful are). Used only by suggest_new_characters' character-only
# ordering, matching seed_brain.FALLBACK_STROKE_COUNT's reasoning: set above
# the median so an unmeasured character sorts as moderately complex rather
# than winning ties by default as if it were trivially simple.
FALLBACK_STROKE_COUNT = 15

# Same cutoff and reasoning as seed_brain.BEGINNER_RANK_CUTOFF: sorting
# suggest_new_characters' character-only phase by stroke count alone would
# surface a rare-but-simple radical like 匕 (2 strokes, frequency rank
# ~3250) or 卜 (2 strokes, ~1980) ahead of everyday characters that just
# happen to have one or two more strokes. This keeps the pool to characters
# actually worth learning, then lets stroke count break ties among those.
BEGINNER_RANK_CUTOFF = 1500

# Most characters one character-only batch may hold.
#
# A batch of real sentences is deliberately small (server.py asks for 3): the
# saved bank is replaced only on an explicit "Get Sentences", so a small batch
# keeps a session finishable and the choice of what to practice next
# deliberate. Applied to character practice that same 3 stranded people. A
# Tier 1 pool is 5 characters, so a 3-item bank covered three of them and
# looped those three forever -- the other two showed in the "Due" badge, which
# reads unlocked_chars directly, but could never come up, because nothing
# refreshes the bank on its own. Practising perfectly made it worse: the more
# reliably they finished the three they had, the longer the two they had never
# seen sat there.
#
# So a character-only batch covers the whole unlocked pool instead. There is
# no session to keep finishable here -- the pool *is* the session -- and
# nothing is gained by hiding part of it. This cap only bites in the
# finding-18 fallback, where a pool of any size can end up in character
# practice; inside the beginner phase proper the pool is below
# CHARACTER_ONLY_UNLOCK_THRESHOLD by definition, so it never truncates.
CHARACTER_ONLY_BATCH_CAP = CHARACTER_ONLY_UNLOCK_THRESHOLD

# How many single characters a *sentence* batch may reserve for unlocked
# characters that no playable sentence contains. See
# JuziEngine._stranded_character_picks for why they exist at all: sentence
# practice can only serve a character inside a sentence the learner can
# already write, so a character can be unlocked, due, and counted in the
# "Due: N" badge while nothing ever puts it in front of them.
#
# One, deliberately. A due single character scores the maximum on _due_ratio,
# so left to rank freely these would fill the batch and turn a sentence
# session into character drill -- most visibly for a large pool carrying rare
# characters from pasted text, where the stranded set can be dozens deep. One
# slot per batch makes every stranded character reachable within a few
# batches while leaving the session sentence-shaped.
STRANDED_CHARACTER_SLOTS = 1

# How far suggest_new_words demotes a word whose characters are all already
# unlocked: it teaches vocabulary but unlocks no new handwriting practice.
# Applied as a multiplier on the frequency rank, so a top-50 word like 你好
# still surfaces early while a rank-3000 one drops out of reach.
KNOWN_CHARS_RANK_PENALTY = 3

# Context-aware pinyin, generated by build_pinyin_readings.py from pypinyin
