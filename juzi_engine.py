class JuziEngine:
    def __init__(self, brain_path="brain.json", words_path="words_freq.json", master_dict_path="master_dictionary.json"):
        self.brain_path = brain_path
        self.words_path = words_path
        self.master_dict_path = master_dict_path
        # server.py now runs requests concurrently (ThreadingHTTPServer), so
        # brain.json's read-modify-write methods (review_character,
        # import_text_locally, add_words, generate_fresh_session) can race:
        # two threads each read the same on-disk state, mutate their own copy,
        # and whichever writes last silently wins -- the other thread's
        # update (a character's SRS progress, a saved sentence) is lost. An
        # RLock (not a plain Lock) because these methods call each other and
        # each other's read-only helpers (e.g. generate_fresh_session ->
        # pick_hsk_sentences -> _read_brain), all on the same thread;
        # a plain Lock would deadlock a thread against itself on the second
        # acquire. Every method that touches self.brain_path holds this for
        # its full read-through-write span, not just around each open().
        self.brain_lock = threading.RLock()

    def load_master_dictionary(self) -> dict:
        """
        The static character reference: pinyin, meaning, and (since the
        frequency data was carried through from hanzi_db.csv) `freq`,
        `strokes` and `hsk`. Cached per path -- the file is ~1.1 MB and this
        runs on per-request paths.

        Treat the returned dict as read-only; every caller shares it.
        """
        cached = _master_dict_cache.get(self.master_dict_path)
        if cached is not None:
            return cached
        with _master_dict_lock:
            cached = _master_dict_cache.get(self.master_dict_path)
            if cached is not None:
                return cached
            data = {}
            if os.path.exists(self.master_dict_path):
                try:
                    with open(self.master_dict_path, "r", encoding="utf-8") as f:
                        data = json.load(f)
                except Exception as e:
                    print(f"Warning: Could not load {self.master_dict_path}: {e}")
            _master_dict_cache[self.master_dict_path] = data
            return data

    def char_frequency_rank(self, char: str) -> int:
        """
        A character's frequency rank (1 = most common), or a large sentinel if
        it isn't in the dictionary, so it sorts last without special-casing.
        """
        meta = self.load_master_dictionary().get(char)
        if not meta:
            return 10 ** 9
        return meta.get("freq") or 10 ** 9

    def daily_new_limit(self, brain_data: dict = None) -> int:
        """How many new characters this account will take on per day."""
        if brain_data is None:
            brain_data = self._read_brain()
        settings = brain_data.get("settings") or {}
        raw = settings.get("daily_new_limit", DEFAULT_DAILY_NEW_LIMIT)
        try:
            value = int(raw)
        except (TypeError, ValueError):
            return DEFAULT_DAILY_NEW_LIMIT
        return max(0, value)

    def study_styles(self, brain_data: dict = None) -> set:
        """
        Which practice item kinds ("characters", "words", "sentences") this
        account currently studies -- editable in Settings, at least one
        always enabled (an empty selection falls back to the full default
        rather than serving nothing, since a config that silently empties
        every session is worse than ignoring a bad save).

        Unknown values (a stale client, hand-edited brain.json) are dropped
        rather than rejected, the same tolerance daily_new_limit's read side
        doesn't need but this one does: there's no numeric range to clamp
        into, just a set to intersect against what's actually valid.
        """
        if brain_data is None:
            brain_data = self._read_brain()
        settings = brain_data.get("settings") or {}
        raw = settings.get("study_styles")
        if not isinstance(raw, list):
            return set(DEFAULT_STUDY_STYLES)
        styles = {s for s in raw if s in VALID_STUDY_STYLES}
        return styles or set(DEFAULT_STUDY_STYLES)

    def total_due_count(self, brain_data: dict = None) -> int:
        """
        The number the top "Due: N" badge shows, restricted to whichever
        study styles are enabled (see study_styles). "Unlocked: N" is
        deliberately not filtered the same way -- it answers "how much have
        I unlocked in total," not "how much of that is in scope right now."

        Characters and Sentences share one term rather than being summed
        separately: a sentence carries no SM-2 schedule of its own (see
        pick_hsk_sentences/count_playable_sentences) -- "a sentence is due"
        has never meant anything but "it contains a due character." Giving
        it a second, independent number would mean a full corpus scan
        (17,000+ rows) on every single character grading, since this badge
        refreshes after each one, not just once per session -- turning
        every keystroke of practice into a multi-file disk scan on a
        1 vCPU/458 MB box. Enabling either or both of Characters/Sentences
        therefore contributes the one cheap due-character count once; only
        Words, which does carry its own independent SM-2 schedule (see
        get_due_words), adds a second, separate term.
        """
        if brain_data is None:
            brain_data = self._read_brain()
        unlocked_chars = brain_data.get("unlocked_chars", {}) or {}
        unlocked_words = brain_data.get("unlocked_words", {}) or {}
        styles = self.study_styles(brain_data)
        new_limit = self.daily_new_limit(brain_data)

        total = 0
        if "characters" in styles or "sentences" in styles:
            total += len(self.get_due_characters(unlocked_chars, new_limit))
        if "words" in styles:
            total += len(self.get_due_words(unlocked_words, new_limit))
        return total

    def read_settings(self) -> dict:
        """
        The settings panel's whole payload: the stored values, the bounds the
        UI should enforce, and enough of today's state to make the number
        mean something ("12 introduced today, 60 waiting") rather than being
        an abstract dial.
        """
        brain_data = self._read_brain()
        unlocked = brain_data.get("unlocked_chars", {}) or {}
        today = date.today().isoformat()
        return {
            "daily_new_limit": self.daily_new_limit(brain_data),
            "default_daily_new_limit": DEFAULT_DAILY_NEW_LIMIT,
            "min_daily_new_limit": MIN_DAILY_NEW_LIMIT,
            "max_daily_new_limit": MAX_DAILY_NEW_LIMIT,
            "introduced_today": sum(1 for m in unlocked.values()
                                    if m.get("introduced") == today),
            "new_backlog": self.new_character_backlog(unlocked),
            "unlocked_chars": len(unlocked),
            "study_styles": sorted(self.study_styles(brain_data)),
        }

    def update_settings(self, values: dict) -> dict:
        """
        Validates and persists settings from the Settings panel, returning
        the same payload read_settings does so the caller can re-render from
        the stored truth rather than from what it hoped it saved.

        Only keys this understands are touched; anything else in `values` is
        ignored rather than written, so a stale or hostile client cannot use
        this endpoint to stuff arbitrary data into brain.json.

        Raises ValueError on a value that isn't a whole number in range --
        the endpoint turns that into a 400. Silently clamping instead would
        be worse: someone typing 500 should be told the cap is 100, not left
        believing they set 500.
        """
        if "daily_new_limit" in values:
            raw = values["daily_new_limit"]
            # bool is an int subclass, and True would quietly become 1.
            if isinstance(raw, bool):
                raise ValueError("'daily_new_limit' must be a whole number.")
            # int(7.5) is 7, so a bare int() would silently truncate a
            # fraction into a valid-looking setting -- the same
            # accept-but-change-it behaviour the range check above refuses.
            # An integral float (7.0) is fine: JSON has no integer type, so
            # that is a spelling of 7 rather than a different value.
            if isinstance(raw, float) and not raw.is_integer():
                raise ValueError("'daily_new_limit' must be a whole number.")
            try:
                limit = int(raw)
            except (TypeError, ValueError):
                raise ValueError("'daily_new_limit' must be a whole number.")
            if not MIN_DAILY_NEW_LIMIT <= limit <= MAX_DAILY_NEW_LIMIT:
                raise ValueError(
                    f"'daily_new_limit' must be between {MIN_DAILY_NEW_LIMIT} "
                    f"and {MAX_DAILY_NEW_LIMIT}.")
        else:
            limit = None

        if "study_styles" in values:
            raw_styles = values["study_styles"]
            if not isinstance(raw_styles, list) or not all(isinstance(s, str) for s in raw_styles):
                raise ValueError("'study_styles' must be a list of strings.")
            styles = {s for s in raw_styles if s in VALID_STUDY_STYLES}
            if not styles:
                raise ValueError(
                    "'study_styles' must include at least one of: "
                    + ", ".join(sorted(VALID_STUDY_STYLES)) + ".")
        else:
            styles = None

        with self.brain_lock:
            brain_data = self._read_brain()
            settings = brain_data.setdefault("settings", {})
            if limit is not None:
                settings["daily_new_limit"] = limit
            if styles is not None:
                settings["study_styles"] = sorted(styles)
            # daily_goal and strict_mode were written into every new brain
            # and read by nothing, ever. They are gone from the schema now
            # (see seed_brain.empty_brain); drop them from existing accounts
            # on the first save rather than shipping a migration script, the
            # same way prune_single_char_words cleans up after finding 5.
            for dead in DEAD_SETTING_KEYS:
                settings.pop(dead, None)
            with open(self.brain_path, "w", encoding="utf-8") as f:
                json.dump(brain_data, f, ensure_ascii=False, indent=4)

        return self.read_settings()

    def _read_brain(self) -> dict:
        """Reads brain.json, returning {} rather than raising if it can't."""
        with self.brain_lock:
            if not os.path.exists(self.brain_path):
                return {}
            try:
                with open(self.brain_path, "r", encoding="utf-8") as f:
                    return json.load(f)
            except Exception as e:
                print(f"Error reading brain database: {e}")
                return {}

    def load_word_frequencies(self) -> dict:
        """Loads the separate static word frequency file safely."""
        if not os.path.exists(self.words_path):
            return {}
        try:
            with open(self.words_path, "r", encoding="utf-8") as f:
                return json.load(f)
        except Exception as e:
            print(f"Warning: Could not load {self.words_path}: {e}")
            return {}

    @staticmethod
    def load_pinyin_readings() -> dict:
        """
        Loads the context-aware pinyin tables, once per process.

        Returns {"phrases": {word: [reading per char]}, "chars": {char:
        [readings, most-common first]}}. Missing file is not an error: every
        caller degrades to master_dictionary.json's single reading, which is
        exactly the pre-existing behaviour, so a clone that hasn't run
        build_pinyin_readings.py still works.
        """
        global _readings_cache
        if _readings_cache is not None:
            return _readings_cache
        with _readings_lock:
            if _readings_cache is not None:      # another thread won the race
                return _readings_cache
            data = {"phrases": {}, "chars": {}}
            if os.path.exists(PINYIN_READINGS_FILE):
                try:
                    with open(PINYIN_READINGS_FILE, "r", encoding="utf-8") as f:
                        loaded = json.load(f)
                    data = {"phrases": loaded.get("phrases", {}),
                            "chars": loaded.get("chars", {})}
                except Exception as e:
                    print(f"Warning: could not load {PINYIN_READINGS_FILE}: {e}")
            else:
                print(f"Notice: {PINYIN_READINGS_FILE} not found -- tier-1 hints "
                      f"will use one reading per character. Run "
                      f"build_pinyin_readings.py to enable context-aware pinyin.")
            _readings_cache = data
            return _readings_cache

    @staticmethod
    def _tone_of(syllable: str) -> int:
        """Tone number 1-4 of a toned pinyin syllable; 0 for neutral tone."""
        for ch in unicodedata.normalize("NFD", syllable):
            if ch in _TONE_MARKS:
                return _TONE_MARKS[ch]
        return 0

    @classmethod
    def _apply_tone_sandhi(cls, chars: list, readings: list) -> list:
        """
        Applies 不 and 一 tone sandhi in place of their citation tones.

        Finding 11: both were previously shown in citation tone regardless of
        context, so a learner reading 我不是 was taught `bù` where a speaker
        says `bú`. The rules:

          不  bù -> bú before a fourth-tone syllable. Unconditional; there is
              no exception worth encoding.
          一  yī -> yí before a fourth tone, yì before first/second/third.
              Suppressed when 一 is being *named* rather than counting: as an
              ordinal (第一), in a number (一九九九年, 十一), before a month
              (一月), or sentence-finally, where it keeps yī.

        Third-tone sandhi (你好 nǐ hǎo spoken ní hǎo) is deliberately NOT
        applied. It is real, but teaching materials and dictionaries write the
        citation tones, and a hint reading `ní` where every textbook shows
        `nǐ` would look like a bug to the learner rather than a lesson.
        """
        out = list(readings)
        for i, char in enumerate(chars):
            if char not in ("不", "一") or not out[i]:
                continue
            nxt = out[i + 1] if i + 1 < len(out) else ""
            next_tone = cls._tone_of(nxt) if nxt else 0

            if char == "不":
                if next_tone == 4:
                    out[i] = "bú"
                continue

            # 一 -- check the suppressing contexts first. These RESET to yī
            # rather than merely skipping, because the phrase table can arrive
            # with sandhi already baked in: pypinyin stores 一月 as yí yuè,
            # right for "one month" but wrong for the month name January.
            prev_char = chars[i - 1] if i > 0 else ""
            next_char = chars[i + 1] if i + 1 < len(chars) else ""
            if (prev_char == "第"
                    or prev_char in _NUMERIC_NEIGHBOURS
                    or next_char in _NUMERIC_NEIGHBOURS
                    or next_char == "月"
                    or not next_char):
                out[i] = "yī"
                continue
            if next_tone == 4:
                out[i] = "yí"
            elif next_tone in (1, 2, 3):
                out[i] = "yì"
        return out

    def pinyin_for_sentence(self, chinese: str, master_dict: dict = None) -> list:
        """
        Per-POSITION pinyin for a sentence: one entry per character of
        `chinese`, "" for punctuation and anything with no known reading.

        This is finding 10's fix. char_metadata was keyed by character, so a
        sentence using 长 in both its readings had nowhere to put the second
        one, and the reading it did store came from master_dictionary.json's
        single-reading table. Resolution order:

          1. Longest-match against the phrase table, so a character inside a
             known word takes that word's reading (行 -> háng in 银行, xíng in
             行走). Longest-match-wins mirrors segment_compounds, for the same
             reason: each position is claimed once, and the longer phrase is
             the more specific context.
          2. The character's most-common reading otherwise.
          3. master_dictionary.json's single reading, if the character is
             absent from the readings file entirely.

        Then tone sandhi is applied over the result (see _apply_tone_sandhi).
        Phrase matching runs within runs of Chinese characters so a phrase can
        never straddle punctuation, again matching segment_compounds.
        """
        chars = list(chinese)
        readings = [""] * len(chars)
        if not chars:
            return readings

        tables = self.load_pinyin_readings()
        phrases, char_table = tables["phrases"], tables["chars"]
        if master_dict is None:
            master_dict = self.load_master_dictionary()
        max_len = max((len(w) for w in phrases), default=0)

        for match in re.finditer(r"[一-龥]+", chinese):
            run, base = match.group(), match.start()
            i = 0
            while i < len(run):
                for length in range(min(max_len, len(run) - i), 1, -1):
                    hit = phrases.get(run[i:i + length])
                    if hit and len(hit) == length:
                        readings[base + i:base + i + length] = hit
                        i += length
                        break
                else:
                    char = run[i]
                    alts = char_table.get(char)
                    if alts:
                        readings[base + i] = alts[0]
                    else:
                        readings[base + i] = master_dict.get(char, {}).get("pinyin", "")
                    i += 1

        return self._apply_tone_sandhi(chars, readings)

    def attach_char_data(self, sentence: dict, unlocked_chars: dict,
                         master_dict: dict = None) -> dict:
        """
        Fills in a sentence's per-character hint data, in place.

        Writes two fields, because they answer different questions and only
        one of them can be keyed by character:

          char_metadata  {char: {pinyin, meaning}} -- the original shape, kept
                         so an older saved brain.json and any client that
                         still reads it keep working. Its `pinyin` remains the
                         single per-character reading; it cannot carry a
                         context-correct one, since a sentence using 长 twice
                         in two readings has only one slot for it. That
                         limitation is finding 10 itself.
          char_pinyin    [reading, ...] parallel to `chinese`, one entry per
                         POSITION ("" for punctuation). This is the field the
                         tier-1 hint should read.

        Both are written every time, so a sentence saved before this existed
        gains char_pinyin the next time it passes through here.
        """
        chinese = sentence.get("chinese", "")
        if master_dict is None:
            master_dict = self.load_master_dictionary()

        char_metadata = {}
        for char in chinese:
            source = unlocked_chars.get(char) or master_dict.get(char) or {}
            char_metadata[char] = {"pinyin": source.get("pinyin", ""),
                                   "meaning": source.get("meaning", "")}

        sentence["char_metadata"] = char_metadata
        sentence["char_pinyin"] = self.pinyin_for_sentence(chinese, master_dict)
        return sentence

    def readings_for_char(self, char: str) -> list:
        """
        Every attested reading for a character, most-common first.

        Used to show the alternatives when a reading is ambiguous, and to let
        callers tell a genuine polyphone from a character that simply has one
        reading. Falls back to master_dictionary.json's single entry.
        """
        alts = self.load_pinyin_readings()["chars"].get(char)
        if alts:
            return list(alts)
        single = self.load_master_dictionary().get(char, {}).get("pinyin", "")
        return [single] if single else []

    def get_due_characters(self, unlocked_chars: dict = None,
                           new_limit: int = None) -> set:
        """
        The unlocked characters due for practice right now: every reviewed
        character whose interval has elapsed, plus a *capped* intake of
        characters never reviewed before. Used to bias which practice
        sentences get picked, rather than treating the whole unlocked pool as
        equally worth practicing.

        The cap is finding 13. Every character unlocked by pasting text or
        adding a word starts with last=None, and all of them counted as due at
        once -- pasting a short story produced "Due: 400" instantly, with no
        ordering and no ceiling. That is not a study plan; it is a wall, and
        the number is demoralising rather than informative. At most
        daily_new_limit characters are now introduced per day, and because
        they are admitted in frequency order the wait is always spent on the
        most useful characters first, which is the whole point of the app.

        Characters already introduced today (see review_character, which
        stamps `introduced` on a character's first grading) count against the
        day's allowance, so finishing today's new characters does not
        immediately conjure a fresh batch.
        """
        brain_data = None
        if unlocked_chars is None:
            brain_data = self._read_brain()
            unlocked_chars = brain_data.get("unlocked_chars", {})
        if new_limit is None:
            new_limit = self.daily_new_limit(brain_data)

        today = date.today()
        today_iso = today.isoformat()
        due = set()
        never_reviewed = []
        introduced_today = 0

        for char, meta in unlocked_chars.items():
            if meta.get("introduced") == today_iso:
                introduced_today += 1

            last = meta.get("last")
            if not last:
                never_reviewed.append(char)
                continue
            try:
                last_date = date.fromisoformat(last)
            except ValueError:
                # An unparseable date means the schedule for this character is
                # meaningless, so treat it as needing review now. It is not a
                # *new* character though -- it has been seen -- so it bypasses
                # the intake cap rather than consuming a day's allowance.
                due.add(char)
                continue
            interval = meta.get("interval", 0) or 0
            if last_date + timedelta(days=interval) <= today:
                due.add(char)

        allowance = max(0, new_limit - introduced_today)
        if allowance and never_reviewed:
            never_reviewed.sort(key=self.char_frequency_rank)
            due.update(never_reviewed[:allowance])
        return due

    def new_character_backlog(self, unlocked_chars: dict = None) -> int:
        """
        How many unlocked characters have never been reviewed and are waiting
        behind the daily intake cap. Reported separately from the due count so
        the UI can say "12 due, 388 waiting" instead of the flat, discouraging
        "Due: 400" that finding 13 was about.
        """
        if unlocked_chars is None:
            unlocked_chars = self._read_brain().get("unlocked_chars", {})
        waiting = [c for c, m in unlocked_chars.items() if not m.get("last")]
        due_new = [c for c in self.get_due_characters(unlocked_chars) if c in set(waiting)]
        return max(0, len(waiting) - len(due_new))

    def get_due_words(self, unlocked_words: dict = None,
                       new_limit: int = None) -> set:
        """
        The unlocked words due for practice right now -- the exact word-side
        mirror of get_due_characters, now that words carry their own
        independent SM-2 schedule (see review_word). Never-reviewed words
        are admitted by frequency `rank` (the word-list equivalent of
        char_frequency_rank) under the same daily_new_limit cap, so a large
        vocabulary import paces itself the same way a large character
        import already did.
        """
        brain_data = None
        if unlocked_words is None:
            brain_data = self._read_brain()
            unlocked_words = brain_data.get("unlocked_words", {})
        if new_limit is None:
            new_limit = self.daily_new_limit(brain_data)

        today = date.today()
        today_iso = today.isoformat()
        due = set()
        never_reviewed = []
        introduced_today = 0

        for word, meta in unlocked_words.items():
            if meta.get("introduced") == today_iso:
                introduced_today += 1

            last = meta.get("last")
            if not last:
                never_reviewed.append(word)
                continue
            try:
                last_date = date.fromisoformat(last)
            except ValueError:
                due.add(word)
                continue
            interval = meta.get("interval", 0) or 0
            if last_date + timedelta(days=interval) <= today:
                due.add(word)

        allowance = max(0, new_limit - introduced_today)
        if allowance and never_reviewed:
            never_reviewed.sort(key=lambda w: unlocked_words[w].get("rank", 99999))
            due.update(never_reviewed[:allowance])
        return due

    def _new_word_budget(self, unlocked_words: dict, brain_data: dict,
                          today_iso: str) -> tuple:
        """(words) -> (never graded at all, how many more may be introduced today). Word-side mirror of _new_character_budget."""
        never_graded = {word for word, meta in unlocked_words.items()
                        if not meta.get("last") and not meta.get("introduced")}
        introduced_today = sum(1 for meta in unlocked_words.values()
                               if meta.get("introduced") == today_iso)
        remaining = max(0, self.daily_new_limit(brain_data) - introduced_today)
        return never_graded, remaining

    @staticmethod
    def _advance_sm2(entry: dict, quality: int, today_iso: str) -> bool:
        """
        Applies one SM-2 grading to `entry` (interval/factor/reps/last) in
        place. Shared by review_character and review_word -- words got their
        own independent SM-2 schedule (Sept 1, 2026, "study words" as its
        own toggleable style) rather than piggybacking on their characters',
        and duplicating this math a second time risked the two schedules
        quietly drifting apart on a future tweak to one but not the other.

        Returns False (entry left untouched) for a same-day successful
        repeat -- see review_character for why that has to be a no-op
        rather than compounding the interval multiplier against itself.
        Quality < 3 always counts, including a same-day repeat: forgetting
        an item later in the same session is real evidence it isn't known.
        """
        already_reviewed_today = entry.get("last") == today_iso
        reps = entry.get("reps", 0) or 0
        interval = entry.get("interval", 0) or 0
        factor = entry.get("factor", 2.5) or 2.5

        if quality < 3:
            reps = 0
            # interval 0, not 1, so the item comes back into the due set
            # *today* rather than tomorrow -- see review_character.
            interval = 0
            factor = max(1.3, factor + (0.1 - (5 - quality) * (0.08 + (5 - quality) * 0.02)))
        elif already_reviewed_today and reps > 0:
            return False
        else:
            if reps == 0:
                interval = 1
            elif reps == 1:
                interval = 6
            else:
                interval = round(interval * factor)
            reps += 1
            factor = max(1.3, factor + (0.1 - (5 - quality) * (0.08 + (5 - quality) * 0.02)))

        entry["reps"] = reps
        entry["interval"] = interval
        entry["factor"] = round(factor, 2)
        entry["last"] = today_iso
        return True

    def review_character(self, char: str, quality: int) -> dict:
        """
        Grades a single completed character quiz and advances its SM-2
        scheduling fields (interval, factor, reps, last) in brain.json.
        quality is 0-5 recall quality (5 = perfect, no hints needed);
        the frontend derives it from how many hint tiers were used.
        Per standard SM-2, quality < 3 counts as a failed recall and resets
        the repetition streak (interval back to 1, reps back to 0) rather
        than advancing the schedule.

        SM-2 assumes at most one grading per item per day. This app can
        easily produce many more: a character often appears twice in one
        sentence (我爱我的妈妈), and the sentence bank loops forever, so a
        single sitting can grade the same character six or more times.
        Advancing on every one of those compounds the interval multiplier
        against itself (1 -> 6 -> 16 -> 45 -> 130 -> 390 days), scheduling a
        character the user has barely learned a year out. So a repeat
        grading on a day the character was already reviewed does not
        advance the schedule (see _advance_sm2). A *failed* repeat still
        applies its lapse: forgetting a character later in the same session
        is real evidence that it isn't known, and ignoring it would let the
        loop paper over genuine failures.
        """
        quality = max(0, min(5, int(quality)))

        with self.brain_lock:
            brain_data = {"unlocked_chars": {}, "sentences": []}
            if os.path.exists(self.brain_path):
                try:
                    with open(self.brain_path, "r", encoding="utf-8") as f:
                        brain_data = json.load(f)
                except Exception as e:
                    print(f"Error reading brain database: {e}")

            unlocked_chars = brain_data.setdefault("unlocked_chars", {})
            entry = unlocked_chars.get(char)
            if entry is None:
                raise ValueError(f"Character '{char}' is not in the unlocked pool.")

            today = date.today().isoformat()

            # First time this character has ever been graded: record the day it
            # entered study. get_due_characters counts these against the daily
            # new-character allowance (finding 13), so working through today's
            # intake doesn't immediately pull the next batch forward.
            brain_data_dirty = False
            if not entry.get("introduced"):
                entry["introduced"] = today
                brain_data_dirty = True

            advanced = self._advance_sm2(entry, quality, today)

            # Persist even when the schedule itself didn't advance (finding
            # 22): the `introduced` stamp set above may be new on this call,
            # and discarding it here would leave introduced_today
            # permanently undercounted and the day's new-character allowance
            # too generous.
            if advanced or brain_data_dirty:
                with open(self.brain_path, "w", encoding="utf-8") as f:
                    json.dump(brain_data, f, ensure_ascii=False, indent=4)

            return {
                "char": char,
                "reps": entry.get("reps", 0),
                "interval": entry.get("interval", 0),
                "factor": entry.get("factor", 2.5),
                "last": entry.get("last"),
                "counted": advanced,
                "due_count": self.total_due_count(brain_data)
            }

    def review_word(self, word: str, quality: int) -> dict:
        """
        Grades a completed word-practice item and advances the word's own
        SM-2 fields in unlocked_words -- independent of any SM-2 grading its
        individual characters separately receive (a word item's characters
        are still written stroke by stroke on the same canvas, and still
        graded via review_character as they're completed; this is an
        additional signal, not a replacement, so writing a word's
        characters keeps teaching those characters even if "words" is the
        only study style enabled). See review_character/_advance_sm2 for
        the scheduling rules themselves, which are identical.
        """
        quality = max(0, min(5, int(quality)))

        with self.brain_lock:
            brain_data = self._read_brain()
            unlocked_words = brain_data.setdefault("unlocked_words", {})
            entry = unlocked_words.get(word)
            if entry is None:
                raise ValueError(f"Word '{word}' is not in the unlocked pool.")

            today = date.today().isoformat()
            brain_data_dirty = False
            if not entry.get("introduced"):
                entry["introduced"] = today
                brain_data_dirty = True

            advanced = self._advance_sm2(entry, quality, today)

            if advanced or brain_data_dirty:
                with open(self.brain_path, "w", encoding="utf-8") as f:
                    json.dump(brain_data, f, ensure_ascii=False, indent=4)

            return {
                "word": word,
                "reps": entry.get("reps", 0),
                "interval": entry.get("interval", 0),
                "factor": entry.get("factor", 2.5),
                "last": entry.get("last"),
                "counted": advanced,
                "due_count": self.total_due_count(brain_data)
            }

    @staticmethod
    def prune_single_char_words(unlocked_words: dict) -> int:
        """
        Drops single-character entries from an unlocked_words map in place,
        returning how many were removed.

        Before compound detection did real segmentation, a bare substring
        scan recorded any of the corpus's 704 single-character entries that
        appeared anywhere in pasted text, so existing installs carry junk
        like 的/是/我 as "studied compound words". Called on the write paths
        so the file heals itself the next time it's saved, rather than
        needing a separate migration script.
        """
        stale = [w for w in unlocked_words if len(w) < 2]
        for word in stale:
            del unlocked_words[word]
        return len(stale)

    def segment_compounds(self, raw_text: str, word_db: dict = None) -> list:
        """
        Finds the compound words from the frequency corpus that actually occur
        in raw_text, as a list of unique words.

        This replaces a bare `word in raw_text` substring scan over all 5,007
        corpus entries, which was wrong in three separate ways:

        * 704 of those entries are *single characters*, so 的/是/我 were
          reported as "compound words the user has studied" -- and then
          recorded in brain.json as exactly that. Words here are length >= 2,
          always.
        * Overlapping matches both fired: 早上 and 上 were each reported for
          the same two characters. Longest-match-wins segmentation consumes
          the text, so each position is claimed once.
        * A substring search ignores punctuation, so a "word" could straddle
          a clause boundary (...喝热茶。他是... spanning the 。). Matching runs
          of Chinese characters means a match can never cross one.

        Greedy longest-match is not a real statistical segmenter and will
        mis-split genuinely ambiguous strings. For "which HSK words appear in
        this pasted text" that tradeoff is fine; it is not jieba.
        """
        if word_db is None:
            word_db = self.load_word_frequencies()

        # Only real corpus words are matchable: "_"-prefixed keys are metadata,
        # and single characters are what this whole method exists to exclude.
        vocab = {w for w in word_db if len(w) >= 2 and not w.startswith("_")}
        if not vocab:
            return []
        max_len = max(len(w) for w in vocab)

        found = []
        seen = set()

        # Runs of Chinese characters, so punctuation, latin text, digits, and
        # newlines all act as boundaries without having to enumerate them.
        for run in re.findall(r"[一-龥]+", raw_text):
            i = 0
            while i < len(run):
                # Longest candidate first, stopping at 2 -- range's exclusive
                # bound of 1 is what keeps single characters unmatchable.
                for length in range(min(max_len, len(run) - i), 1, -1):
                    candidate = run[i:i + length]
                    if candidate in vocab:
                        if candidate not in seen:
                            seen.add(candidate)
                            found.append(candidate)
                        i += length
                        break
                else:
                    i += 1

        return found

    def analyze_text_compounds(self, raw_text: str) -> list:
        """
        Scans text and cross-references the separate static word frequency database
        to identify high-frequency compound words present in the input.
        """
        word_db = self.load_word_frequencies()

        found_words = [
            {
                "word": word,
                "pinyin": word_db[word].get("pinyin", ""),
                "meaning": word_db[word].get("meaning", ""),
                "rank": word_db[word].get("rank", 99999),
            }
            for word in self.segment_compounds(raw_text, word_db)
        ]

        # Sort discovered words by natural corpus usage frequency rank
        found_words.sort(key=lambda x: x["rank"])
        return found_words

    @staticmethod
    def _split_vocab_line(line: str):
        """
        Splits one line that carries both Chinese and English on it -- with a
        separator ("\u4f60\u597d - hello", "\u4f60\u597d: hello") or without one ("\u4f60\u597d hello") -- into
        (chinese, english). Splits at the line's first Latin letter: unlike
        looking for a specific delimiter, that works regardless of which
        punctuation (if any) a given list happens to use. Everything before
        the split is stripped of a leading list marker ("1.", "b)") and any
        trailing separator punctuation; everything from the split onward is
        stripped of a leading separator. Returns None if the line doesn't
        actually carry both scripts, or if either side is empty once
        stripped (a bare list marker, or trailing punctuation with nothing
        after it).
        """
        if not (_CJK_CHAR_RE.search(line) and _LATIN_LETTER_RE.search(line)):
            return None
        split_at = _LATIN_LETTER_RE.search(line).start()
        chinese_part = _LEADING_LIST_MARKER_RE.sub("", line[:split_at])
        chinese_part = _TRAILING_SEPARATOR_RE.sub("", chinese_part).strip()
        english_part = _LEADING_SEPARATOR_RE.sub("", line[split_at:]).strip()
        if not chinese_part or not english_part:
            return None
        return (chinese_part, english_part)

    def _pair_vocab_lines(self, raw_text: str):
        """
        Turns one combined Chinese/English paste into (chinese, english)
        pairs, the way a vocab list or set of example sentences actually
        arrives: Chinese and English sharing a line (see _split_vocab_line),
        or Chinese on its own line immediately followed by its English on
        the next non-blank line. A Chinese-only line with no recognizable
        English anywhere nearby is reported back in the second return value
        rather than guessed at -- its characters still get unlocked by
        import_text_locally's separate character scan, it just isn't saved
        as a practice sentence.

        Returns (pairs, unpaired_chinese_lines).
        """
        lines = raw_text.splitlines()
        pairs = []
        unpaired = []
        i, n = 0, len(lines)
        while i < n:
            line = lines[i].strip()
            if not line:
                i += 1
                continue

            same_line = self._split_vocab_line(line)
            if same_line:
                pairs.append(same_line)
                i += 1
                continue

            if _CJK_CHAR_RE.search(line) and not _LATIN_LETTER_RE.search(line):
                j = i + 1
                while j < n and not lines[j].strip():
                    j += 1
                next_line = lines[j].strip() if j < n else ""
                if next_line and _LATIN_LETTER_RE.search(next_line) and not _CJK_CHAR_RE.search(next_line):
                    chinese_part = _LEADING_LIST_MARKER_RE.sub("", line).strip()
                    if chinese_part:
                        pairs.append((chinese_part, next_line))
                        i = j + 1
                        continue
                unpaired.append(line)
                i += 1
                continue

            # Latin-only, or otherwise unclassifiable, with no preceding
            # Chinese-only line waiting for it -- nothing to pair it against.
            i += 1

        return pairs, unpaired

    def import_text_locally(self, raw_text: str) -> dict:
        """
        Parses one combined Chinese/English paste, extracts unique Chinese
        characters, pulls their pinyin/meanings instantly from the local
        master_dictionary, and updates brain.json. Also scans for compound
        words via the static word frequency database.

        Also saves whatever Chinese/English pairs _pair_vocab_lines can find
        in the same paste as practice sentences, into brain.json's
        pasted_sentences -- a persistent personal corpus (unlike the
        ephemeral `sentences` bank, which generate_fresh_session overwrites
        wholesale on every new batch) that pick_hsk_sentences draws from
        alongside the built-in corpora, so a user's own imported material
        keeps resurfacing in practice.

        There used to be a second, separate translation textarea, paired with
        this one by line position. It was replaced (per explicit user
        decision) with a single box plus automatic pairing, because the
        realistic input -- a vocab list or a set of example sentences pasted
        from somewhere else -- already carries the English right next to each
        Chinese entry, either on the same line or the line directly below it,
        and making the user copy it into a second box was pure friction.
        """
        chinese_chars = set(re.findall(r'[\u4e00-\u9fa5]', raw_text))

        with self.brain_lock:
            # Load existing brain database
            brain_data = {"unlocked_chars": {}, "unlocked_words": {}, "sentences": []}
            if os.path.exists(self.brain_path):
                try:
                    with open(self.brain_path, "r", encoding="utf-8") as f:
                        brain_data = json.load(f)
                except Exception as e:
                    print(f"Error reading brain database: {e}")

            # master_dictionary now lives in its own tracked file (master_dictionary.json),
            # not inside gitignored brain.json -- drop any stale embedded copy on save.
            brain_data.pop("master_dictionary", None)

            unlocked = brain_data.setdefault("unlocked_chars", {})
            unlocked_words = brain_data.setdefault("unlocked_words", {})

            # Rejected before pruning/compound-scanning (the expensive, input-
            # length-proportional work below) so an oversized paste costs
            # only this cheap length check, not a scan of the whole thing.
            if len(raw_text) > MAX_IMPORT_TOTAL_CHARS:
                return {
                    "added_count": 0,
                    "total_unlocked_count": len(unlocked),
                    "message": (
                        f"That's too much to paste at once (max {MAX_IMPORT_TOTAL_CHARS} characters "
                        "total, Chinese and English combined). Try a few paragraphs at a time instead."
                    ),
                }

            pruned_word_count = self.prune_single_char_words(unlocked_words)
            master = self.load_master_dictionary()

            if not chinese_chars:
                return {
                    "added_count": 0,
                    "total_unlocked_count": len(unlocked),
                    "message": "No Chinese characters found in input text."
                }

            added_count = 0
            missing_chars = []

            for char in chinese_chars:
                if char not in unlocked:
                    if char in master:
                        unlocked[char] = {
                            "pinyin": master[char].get("pinyin", ""),
                            "meaning": master[char].get("meaning", ""),
                            "interval": 0,
                            "factor": 2.5,
                            "reps": 0,
                            "last": None
                        }
                        added_count += 1
                    else:
                        missing_chars.append(char)

            # Every compound word the frequency database recognizes in the pasted
            # text is recorded in unlocked_words too, not just its individual
            # characters -- so it counts as "already studied" and won't be
            # suggested again by the Suggest Words tab.
            compounds = self.analyze_text_compounds(raw_text)
            added_word_count = 0
            for item in compounds:
                word = item["word"]
                if word not in unlocked_words:
                    unlocked_words[word] = {
                        "pinyin": item.get("pinyin", ""),
                        "meaning": item.get("meaning", ""),
                        "rank": item.get("rank", 99999),
                        "interval": 0,
                        "factor": 2.5,
                        "reps": 0,
                        "last": None,
                    }
                    added_word_count += 1

            # Auto-detect Chinese/English pairs directly out of the single
            # pasted blob and save them into the user's persistent
            # pasted_sentences. See _pair_vocab_lines for the two shapes it
            # recognizes (same line, or Chinese then English on the next).
            saved_sentence_count = 0
            skipped_sentence_count = 0
            oversized_sentence_count = 0
            pairs, unpaired_lines = self._pair_vocab_lines(raw_text)

            pasted_sentences = brain_data.setdefault("pasted_sentences", [])
            existing_chinese = {s.get("chinese") for s in pasted_sentences}

            for chi, eng in pairs:
                chi = re.sub(r'\s+', '', chi)
                eng = eng.strip()
                if not chi or not eng or chi in existing_chinese:
                    continue
                # A practice item is written by hand one character at a
                # time, so an over-long one is not a hard sentence, it is
                # an unfinishable one -- and personal sentences outrank the
                # whole corpus, so it would be served first (finding 19).
                if len(re.findall(r'[一-龥]', chi)) > MAX_PASTED_SENTENCE_CHARS:
                    oversized_sentence_count += 1
                    continue
                # Every Chinese character in the sentence must already be
                # unlockable (present in unlocked, which by now holds every
                # character from raw_text that's in master_dictionary) --
                # otherwise it can never be shown on the canvas with real
                # pinyin/meaning, so the pair isn't worth saving.
                if not all(c in unlocked for c in re.findall(r'[一-龥]', chi)):
                    skipped_sentence_count += 1
                    continue
                pasted_sentences.append({"chinese": chi, "english": eng})
                existing_chinese.add(chi)
                saved_sentence_count += 1

            # Save updates back to brain.json
            with open(self.brain_path, "w", encoding="utf-8") as f:
                json.dump(brain_data, f, ensure_ascii=False, indent=4)

            total_unlocked = len(unlocked)

        msg = f"Instantly unlocked {added_count} characters locally! Total active pool: {total_unlocked}."
        if compounds:
            msg += f" Found {len(compounds)} high-frequency compound words ({added_word_count} new)."
        if missing_chars:
            msg += f" ({len(missing_chars)} chars missing from master dictionary)."
        if pruned_word_count:
            msg += f" (Cleaned up {pruned_word_count} single-character entries wrongly stored as words.)"
        if saved_sentence_count:
            msg += f" Saved {saved_sentence_count} sentence(s) to your personal practice bank."
        if skipped_sentence_count:
            msg += f" ({skipped_sentence_count} sentence(s) skipped -- contain characters outside the master dictionary.)"
        if oversized_sentence_count:
            msg += (f" ({oversized_sentence_count} sentence(s) skipped -- longer than "
                    f"{MAX_PASTED_SENTENCE_CHARS} characters, which is more than anyone "
                    "should hand-write as one practice item. Put each sentence on its "
                    "own line to save them separately.)")
        if unpaired_lines:
            preview = "、".join(unpaired_lines[:5])
            if len(unpaired_lines) > 5:
                preview += f", and {len(unpaired_lines) - 5} more"
            msg += (f" Characters were unlocked, but no English translation was found for: {preview} "
                    "-- so these weren't saved as practice sentences. Put the English right after "
                    "each one (same line or the line below) to have them saved too.")

        return {
            "added_count": added_count,
            "total_unlocked_count": total_unlocked,
            "compounds_detected": compounds,
            "added_word_count": added_word_count,
            "pruned_word_count": pruned_word_count,
            "saved_sentence_count": saved_sentence_count,
            "skipped_sentence_count": skipped_sentence_count,
            "oversized_sentence_count": oversized_sentence_count,
            "unpaired_line_count": len(unpaired_lines),
            "message": msg
        }

    def suggest_new_words(self, count: int = 5) -> list:
        """
        Suggests the highest-frequency compound words from words_freq.json
        that the user hasn't already added to their vocabulary (tracked via
        brain.json's unlocked_words), so vocabulary growth follows real-world
        usage frequency rather than random order.
        """
        word_db = self.load_word_frequencies()

        with self.brain_lock:
            known_words = {}
            unlocked_chars = {}
            if os.path.exists(self.brain_path):
                try:
                    with open(self.brain_path, "r", encoding="utf-8") as f:
                        brain_data = json.load(f)
                    known_words = brain_data.get("unlocked_words", {})
                    unlocked_chars = brain_data.get("unlocked_chars", {})
                except Exception as e:
                    print(f"Error reading brain database: {e}")

        candidates = [
            {
                "word": word,
                "pinyin": meta.get("pinyin", ""),
                "meaning": meta.get("meaning", ""),
                "rank": meta.get("rank", 99999),
                # A word every one of whose characters is already unlocked is
                # still worth learning -- it teaches the compound's meaning --
                # but it buys no new practice material, so it's demoted rather than
                # dropped. The demotion is a multiplier on the frequency rank,
                # not a separate bucket: bucketing sorts *every* word that
                # unlocks a character above *every* word that doesn't, and
                # since almost all 5,007 corpus words contain some character
                # you haven't unlocked, that buries 你好 thousands of entries
                # deep -- exclusion wearing a different hat. Scaling the rank
                # keeps very common known-character words near the top while
                # still letting rarer ones fall behind.
                "_sort_rank": meta.get("rank", 99999) * (
                    1 if any(c not in unlocked_chars for c in word) else KNOWN_CHARS_RANK_PENALTY
                ),
            }
            # len >= 2 is the same filter segment_compounds applies: 704 of the
            # corpus's 5,007 entries are single characters, which is why this
            # tab used to suggest 是/我/的 as "compound words".
            for word, meta in word_db.items()
            if len(word) >= 2 and not word.startswith("_") and word not in known_words
        ]
        candidates.sort(key=lambda x: x["_sort_rank"])
        top = candidates[:count]
        for c in top:
            del c["_sort_rank"]
        return top

    def sentences_unlocked_by(self, unlocked_set: set) -> dict:
        """
        For every character NOT yet unlocked, how many corpus sentences would
        become playable if it alone were added -- i.e. sentences whose only
        missing character is that one.

        HSK mode only serves a sentence when *every* character in it is
        unlocked, so an isolated character can be perfectly frequent and still
        buy no practice at all. This is the same insight seed_brain.py uses to
        pick a starter pool (raw frequency yields all function words and zero
        playable sentences); this exposes it in the running app so the Suggest
        Characters tab can say what a character is actually worth right now.

        One pass over the corpus rather than a scan per candidate: each
        sentence with exactly one missing character credits that character.
        """
        allowed_punct = "，。！？、；：“”‘’—…"
        credit = {}
        for filename in SENTENCE_SOURCE_FILES:
            if not os.path.exists(filename):
                continue
            try:
                with open(filename, "r", encoding="utf-8") as f:
                    for row in csv.DictReader(f, delimiter="\t"):
                        chinese = (row.get("sentence") or "").replace(" ", "").strip()
                        if not chinese or not (row.get("sentence_meaning") or "").strip():
                            continue
                        missing = set()
                        for char in chinese:
                            if char in unlocked_set or char in allowed_punct:
                                continue
                            missing.add(char)
                            if len(missing) > 1:
                                break
                        if len(missing) == 1:
                            char = missing.pop()
                            credit[char] = credit.get(char, 0) + 1
            except Exception as e:
                print(f"Warning: could not read {filename}: {e}")
        return credit

    def suggest_new_characters(self, count: int = 8) -> list:
        """
        The most useful characters the user hasn't unlocked yet.

        The app's whole premise is learning to write the most frequently used
        characters, but until now the only way in was pasting text or adding a
        compound word -- there was no way to ask the direct question, "what is
        the most useful character I don't know yet?". Suggest Words answers it
        for vocabulary; this answers it for the actual practice unit.

        Ranked by frequency, but reported alongside `unlocks`, the number of
        corpus sentences that become playable the moment this character is
        added (see sentences_unlocked_by). Both numbers matter and they
        disagree often: a top-100 character that completes no sentence buys no
        practice today, while a rarer one that completes forty is immediately
        useful. Showing both lets the learner choose rather than hiding the
        trade-off behind a single opaque score.

        Below CHARACTER_ONLY_UNLOCK_THRESHOLD, `unlocks` is not actually a
        signal of anything -- pick_hsk_sentences won't show a single sentence
        until the pool crosses that threshold (finding: a Tier 1 account
        chasing the "completes a sentence" bonus was getting handed rare,
        high-stroke characters like 睏 (12 strokes, frequency rank ~7300)
        ahead of 的 (8 strokes, rank 1), because 睏 happened to complete one
        of the few short sentences reachable from a five-character pool -- a
        sentence that couldn't be played yet regardless. Simplicity and
        frequency are what actually matter while the user is still in
        character-only practice, so this phase sorts by stroke count first,
        the same philosophy select_beginner_characters uses for Tier 1's
        initial five.
        """
        master = self.load_master_dictionary()
        brain_data = self._read_brain()
        unlocked = brain_data.get("unlocked_chars", {})
        unlocked_set = set(unlocked)
        character_only_phase = len(unlocked_set) < CHARACTER_ONLY_UNLOCK_THRESHOLD

        credit = self.sentences_unlocked_by(unlocked_set)

        candidates = []
        for char, meta in master.items():
            if char in unlocked_set:
                continue
            rank = meta.get("freq")
            if not rank:
                continue
            candidates.append({
                "char": char,
                "pinyin": meta.get("pinyin", ""),
                "meaning": meta.get("meaning", ""),
                "freq": rank,
                "strokes": meta.get("strokes"),
                "hsk": meta.get("hsk"),
                "unlocks": credit.get(char, 0),
            })

        if character_only_phase:
            # Simplicity first, same as Tier 1's initial five -- no sentence
            # is playable yet regardless of `unlocks`. Restricted to
            # BEGINNER_RANK_CUTOFF first so a rare-but-simple character can't
            # outrank a common one just for being easy to draw.
            candidates = [c for c in candidates if c["freq"] <= BEGINNER_RANK_CUTOFF]
            candidates.sort(key=lambda c: (c["strokes"] or FALLBACK_STROKE_COUNT, c["freq"]))
        else:
            # Frequency order, but a character that immediately opens up
            # practice sentences is surfaced ahead of an equally-ranked one
            # that doesn't.
            candidates.sort(key=lambda c: (c["unlocks"] == 0, c["freq"]))
        return candidates[:count]

    def add_characters(self, chars: list) -> dict:
        """
        Unlocks the given characters directly, without needing a compound word
        or a paste to carry them in. Skips anything already unlocked or absent
        from master_dictionary.json (there would be no pinyin or meaning to
        show, and no way to grade it).
        """
        master = self.load_master_dictionary()

        with self.brain_lock:
            brain_data = self._read_brain()
            unlocked = brain_data.setdefault("unlocked_chars", {})
            brain_data.setdefault("unlocked_words", {})

            added, skipped = [], []
            for char in chars:
                if not isinstance(char, str) or len(char) != 1:
                    skipped.append(char)
                    continue
                if char in unlocked:
                    continue
                if char not in master:
                    skipped.append(char)
                    continue
                unlocked[char] = {
                    "pinyin": master[char].get("pinyin", ""),
                    "meaning": master[char].get("meaning", ""),
                    "interval": 0,
                    "factor": 2.5,
                    "reps": 0,
                    "last": None,
                }
                added.append(char)

            with open(self.brain_path, "w", encoding="utf-8") as f:
                json.dump(brain_data, f, ensure_ascii=False, indent=4)

            return {
                "added_chars": added,
                "skipped": skipped,
                "total_unlocked_count": len(unlocked),
                "total_due_count": self.total_due_count(brain_data),
                "new_backlog": self.new_character_backlog(unlocked),
            }

    def add_words(self, words: list) -> dict:
        """
        Adds the given compound words to brain.json's unlocked_words (so
        future suggestions skip them) and unlocks any of their individual
        characters that aren't already unlocked, so the new words are
        immediately available for handwriting practice sentences.
        """
        word_db = self.load_word_frequencies()
        master = self.load_master_dictionary()

        with self.brain_lock:
            brain_data = {"unlocked_chars": {}, "unlocked_words": {}, "sentences": []}
            if os.path.exists(self.brain_path):
                try:
                    with open(self.brain_path, "r", encoding="utf-8") as f:
                        brain_data = json.load(f)
                except Exception as e:
                    print(f"Error reading brain database: {e}")

            unlocked_words = brain_data.setdefault("unlocked_words", {})
            unlocked_chars = brain_data.setdefault("unlocked_chars", {})
            pruned_word_count = self.prune_single_char_words(unlocked_words)

            added_words = []
            rejected_single_chars = []
            added_chars = 0

            for word in words:
                meta = word_db.get(word)
                # len >= 2 guards the endpoint itself, not just the suggestions
                # feeding it: /api/suggestions/add takes an arbitrary word list
                # from the client, and a single character is a character, not a
                # compound word -- unlocked_chars is where those belong. Reported
                # back rather than dropped silently: a stale browser tab holding
                # pre-fix suggestions would otherwise submit them and be told
                # "Added 0 words" with no reason given. Single-character words are
                # a real thing (猫, 水, 茶) -- they're learned by pasting them into
                # the Paste Text tab, which unlocks them for practice directly.
                if meta and len(word) < 2:
                    rejected_single_chars.append(word)
                    continue
                if not meta or word in unlocked_words:
                    continue

                unlocked_words[word] = {
                    "pinyin": meta.get("pinyin", ""),
                    "meaning": meta.get("meaning", ""),
                    "rank": meta.get("rank", 99999),
                    "interval": 0,
                    "factor": 2.5,
                    "reps": 0,
                    "last": None,
                }
                added_words.append(word)

                for char in word:
                    if char not in unlocked_chars and char in master:
                        unlocked_chars[char] = {
                            "pinyin": master[char].get("pinyin", ""),
                            "meaning": master[char].get("meaning", ""),
                            "interval": 0,
                            "factor": 2.5,
                            "reps": 0,
                            "last": None,
                        }
                        added_chars += 1

            with open(self.brain_path, "w", encoding="utf-8") as f:
                json.dump(brain_data, f, ensure_ascii=False, indent=4)

        return {
            "added_words": added_words,
            "added_chars_count": added_chars,
            "total_unlocked_count": len(unlocked_chars),
            "total_words_count": len(unlocked_words),
            "pruned_word_count": pruned_word_count,
            "rejected_single_chars": rejected_single_chars,
        }

    # Frequency bands the progress view reports coverage against. The point of
    # the app is the most-used characters, so "how far into the frequency list
    # am I" is the single most meaningful measure of progress it can offer --
    # far more than a raw unlocked count, which says nothing about whether
    # those characters are the useful ones.
    FREQUENCY_BANDS = [100, 500, 1000, 2000, 3000, 5000]

    def progress_summary(self) -> dict:
        """
        Everything the progress view needs, in one request.

        The app accumulated a lot of state a learner could never see: SM-2
        intervals, ease factors, which characters were mature, how much of the
        frequency list was covered. All of it existed and none of it was
        visible, so there was no way to answer "am I getting anywhere?" -- the
        main thing that keeps someone going on a months-long project.
        """
        brain_data = self._read_brain()
        unlocked = brain_data.get("unlocked_chars", {})
        words = brain_data.get("unlocked_words", {})
        completed = brain_data.get("completed_sentences", {}) or {}
        master = self.load_master_dictionary()

        # Word Bank tab: every unlocked compound (see analyze_text_compounds
        # and add_word), most-common-first. A single character never lands in
        # unlocked_words -- that's what unlocked_chars is -- so no length
        # filter is needed here, but one guards against any legacy entry.
        word_list = sorted(
            ({"word": w, "pinyin": m.get("pinyin", ""), "meaning": m.get("meaning", ""),
              "rank": m.get("rank", 99999)}
             for w, m in words.items() if len(w) >= 2),
            key=lambda w: (w["rank"], w["word"])
        )

        # Sentence Bank tab: everything accrued, not the live practice queue
        # (see generate_fresh_session) -- a "bank" should read like Character
        # Bank and Word Bank, a permanent record of what's been learned, not a
        # view that empties out the moment a new batch is generated (a Paste
        # Text import used to look like it vanished for exactly this reason,
        # since a fresh sentence sits in pasted_sentences long before it's
        # ever pulled into the queue). Two sources, merged: every personal
        # sentence the learner saved via Paste Text (real content they chose
        # to study, shown whether or not they've practiced it yet -- same
        # treatment as an unlocked word that hasn't come up in a session), and
        # every corpus sentence recorded in completed_sentences, most
        # recently finished first. Excludes the one-character stand-ins
        # _character_candidate produces (beginner-phase character-only
        # batches, and the stranded-character slot a sentence batch reserves
        # -- see _stranded_character_picks) -- those are real practice items
        # on the writing screen, but a bank labelled "Sentence Bank" showing a
        # lone 力 or 十 reads as a data bug, not a feature.
        pasted_for_bank = brain_data.get("pasted_sentences", []) or []
        sentence_bank = []
        seen_chinese = set()
        for item in pasted_for_bank:
            chinese = (item.get("chinese") or "").strip()
            english = (item.get("english") or "").strip()
            if not chinese or not english or chinese in seen_chinese or len(chinese) < 2:
                continue
            seen_chinese.add(chinese)
            record = completed.get(chinese) or {}
            sentence_bank.append({
                "chinese": chinese, "english": english, "personal": True,
                "times_completed": record.get("count", 0),
                "last_completed": record.get("last"),
            })

        remaining_completed = {c: m for c, m in completed.items() if c not in seen_chinese}
        corpus_english = self._corpus_english_lookup(set(remaining_completed))
        for chinese, meta in sorted(remaining_completed.items(),
                                     key=lambda kv: kv[1].get("last") or "", reverse=True):
            english = corpus_english.get(chinese)
            if not english or len(chinese) < 2:
                continue
            sentence_bank.append({
                "chinese": chinese, "english": english, "personal": False,
                "times_completed": meta.get("count", 0),
                "last_completed": meta.get("last"),
            })

        today = date.today()
        due = self.get_due_characters(unlocked)

        # Study stages. Thresholds follow the usual spaced-repetition reading:
        # under a week is still being learned, under three weeks is holding but
        # not proven, beyond that is genuinely retained. Built in the same pass
        # as `character_list` below (the per-character "what have I learned"
        # refresher view) so the stage-threshold logic exists in one place.
        stages = {"new": 0, "learning": 0, "young": 0, "mature": 0}
        factors, intervals = [], []
        forecast = {}
        character_list = []
        for char, meta in unlocked.items():
            last = meta.get("last")
            interval = meta.get("interval", 0) or 0
            if not last:
                stage = "new"
            elif interval < 7:
                stage = "learning"
            elif interval < 21:
                stage = "young"
            else:
                stage = "mature"
            stages[stage] += 1

            character_list.append({
                "char": char,
                "pinyin": meta.get("pinyin", ""),
                "meaning": meta.get("meaning", ""),
                "stage": stage,
                "freq": master.get(char, {}).get("freq"),
            })

            if not last:
                continue
            factors.append(meta.get("factor", 2.5) or 2.5)
            intervals.append(interval)
            try:
                next_due = date.fromisoformat(last) + timedelta(days=interval)
            except ValueError:
                continue
            offset = (next_due - today).days
            if 0 < offset <= 14:
                forecast[offset] = forecast.get(offset, 0) + 1

        # Most-common-first -- the same ordering the frequency-coverage bars
        # above use, and the most useful order for a "what have I learned"
        # skim: characters you'll actually encounter soonest come first.
        # Characters absent from master_dictionary's freq data (rare, but the
        # dictionary isn't guaranteed exhaustive) sort last rather than first.
        character_list.sort(key=lambda c: (c["freq"] if c["freq"] is not None else float("inf"), c["char"]))

        # Coverage of the frequency list: the headline number for this app.
        ranked = [(meta.get("freq"), char) for char, meta in master.items()
                  if meta.get("freq")]
        frequency_bands = []
        for band in self.FREQUENCY_BANDS:
            in_band = [c for rank, c in ranked if rank <= band]
            known = sum(1 for c in in_band if c in unlocked)
            frequency_bands.append({"band": band, "known": known,
                                    "total": len(in_band)})

        hsk_levels = {}
        for char, meta in master.items():
            level = meta.get("hsk")
            if not level:
                continue
            bucket = hsk_levels.setdefault(level, {"level": level, "known": 0, "total": 0})
            bucket["total"] += 1
            if char in unlocked:
                bucket["known"] += 1

        return {
            "unlocked_chars": len(unlocked),
            "unlocked_words": len(words),
            "due_count": len(due),
            "new_backlog": self.new_character_backlog(unlocked),
            "daily_new_limit": self.daily_new_limit(brain_data),
            "stages": stages,
            "avg_factor": round(sum(factors) / len(factors), 2) if factors else None,
            "avg_interval": round(sum(intervals) / len(intervals), 1) if intervals else None,
            "frequency_bands": frequency_bands,
            "hsk_levels": [hsk_levels[k] for k in sorted(hsk_levels)],
            "sentences_completed_unique": len(completed),
            "sentences_completed_total": sum(
                (e.get("count", 0) or 0) for e in completed.values()),
            # Reported so the Start Over tab can name what a reset destroys.
            # Everything else here is re-derivable -- reseed a tier and the
            # characters come back -- but these are sentences the user typed
            # in from their own reading, and nothing can reconstruct them.
            "pasted_sentences": len(brain_data.get("pasted_sentences", []) or []),
            "playable_sentences": self.count_playable_sentences(set(unlocked)),
            "forecast": [{"in_days": d, "count": forecast.get(d, 0)}
                         for d in range(1, 15)],
            "characters": character_list,
            "words": word_list,
            "sentence_bank": sentence_bank,
        }

    def _corpus_english_lookup(self, chinese_set: set) -> dict:
        """
        Chinese sentence text -> English translation, scanned once from the
        built-in corpora, for just the sentences named in chinese_set.

        Used to give completed_sentences (which stores only the Chinese text,
        a count, and a date -- see record_sentence_completion) an English
        side to display in the Sentence Bank. Stops scanning a file early
        once every requested sentence has been found.
        """
        found = {}
        if not chinese_set:
            return found
        remaining = set(chinese_set)
        for filename in SENTENCE_SOURCE_FILES:
            if not remaining or not os.path.exists(filename):
                continue
            try:
                with open(filename, "r", encoding="utf-8") as f:
                    for row in csv.DictReader(f, delimiter="\t"):
                        chinese = (row.get("sentence") or "").replace(" ", "").strip()
                        if chinese in remaining:
                            english = (row.get("sentence_meaning") or "").strip()
                            if english:
                                found[chinese] = english
                                remaining.discard(chinese)
            except Exception as e:
                print(f"Warning: could not read {filename}: {e}")
        return found

    def count_playable_sentences(self, unlocked_set: set) -> int:
        """
        How many corpus sentences are fully writable with the current pool.
        The practical ceiling on how much practice material exists right now,
        which is what makes the frequency-coverage numbers concrete.
        """
        allowed_punct = "，。！？、；：“”‘’—…"
        total = 0
        for filename in SENTENCE_SOURCE_FILES:
            if not os.path.exists(filename):
                continue
            try:
                with open(filename, "r", encoding="utf-8") as f:
                    for row in csv.DictReader(f, delimiter="\t"):
                        chinese = (row.get("sentence") or "").replace(" ", "").strip()
                        if not chinese or not (row.get("sentence_meaning") or "").strip():
                            continue
                        if all(c in unlocked_set or c in allowed_punct for c in chinese):
                            total += 1
            except Exception as e:
                print(f"Warning: could not read {filename}: {e}")
        return total

    def record_sentence_completion(self, chinese: str) -> dict:
        """
        Records that a sentence was written all the way through.

        Finding 12: nothing remembered what had been practiced, so batches
        re-served sentences the user had just finished, and `nextSentence`
        loops the bank forever. With a 17,000-sentence corpus the pool is
        rarely exhausted, but that was never the real complaint -- the
        complaint is that a sentence you completed a minute ago is exactly as
        likely to come back as one you have never seen.

        Stored as a count and a date per sentence, keyed by the Chinese text
        itself, so it survives the sentence bank being replaced wholesale on
        every new batch. pick_hsk_sentences reads it to prefer unseen material
        (see its freshness tier).
        """
        chinese = (chinese or "").strip()
        if not chinese:
            return {"recorded": False}

        today = date.today().isoformat()
        with self.brain_lock:
            brain_data = self._read_brain()
            completed = brain_data.setdefault("completed_sentences", {})
            entry = completed.get(chinese) or {}
            entry["count"] = (entry.get("count", 0) or 0) + 1
            entry["last"] = today
            completed[chinese] = entry

            with open(self.brain_path, "w", encoding="utf-8") as f:
                json.dump(brain_data, f, ensure_ascii=False, indent=4)

        return {"recorded": True, "chinese": chinese,
                "count": entry["count"], "last": entry["last"],
                "total_completed": len(completed)}

    def _new_character_budget(self, unlocked_chars: dict, brain_data: dict,
                              today_iso: str) -> tuple:
        """
        (characters never graded at all, how many more may be introduced today).

        Finding 17. get_due_characters already caps how many never-reviewed
        characters enter the *due set*, which is what the "Due: N" badge
        reports -- but that cap never reached the place where practice
        material is actually chosen. pick_hsk_sentences served any sentence
        whose characters were all unlocked, so a learner told "Due: 15" was
        handed 37 characters they had never seen in a 15-sentence session,
        and 98 in a longer one. The badge shrank; the workload did not. This
        gives sentence selection the same budget the badge is drawn from.

        "Never graded" means no `last` AND no `introduced`, not just a
        missing `introduced`: brains written before that field existed carry
        real review history under `last` alone (see finding 22), and treating
        those characters as brand new would spend the whole day's allowance
        re-introducing characters the learner already knows.
        """
        never_graded = {char for char, meta in unlocked_chars.items()
                        if not meta.get("last") and not meta.get("introduced")}
        introduced_today = sum(1 for meta in unlocked_chars.values()
                               if meta.get("introduced") == today_iso)
        remaining = max(0, self.daily_new_limit(brain_data) - introduced_today)
        return never_graded, remaining

    @staticmethod
    def _fill_batch(candidates: list, count: int, budget: int) -> list:
        """
        Takes up to `count` sentences off an already-ranked list, spending at
        most `budget` never-graded characters across the batch as a whole.

        The budget is tracked across the batch, not per sentence: three
        sentences introducing five new characters each is fifteen new
        characters, however comfortably each one fits on its own. Characters
        already spent earlier in the same batch are free afterwards, since
        the learner meets them once.

        **Soft cap, never a starved session.** If fewer than `count`
        sentences fit the budget, the batch is topped up from the same ranked
        list ignoring it. A hard filter would be the more faithful reading of
        a daily limit, but it can empty the pool outright on a small
        character set -- which is finding 18's failure arriving by another
        route, and an empty session teaches nothing at all. Overshooting the
        cap is the lesser harm, and it only happens when respecting it would
        mean serving nothing.
        """
        picked, chosen, spent = [], set(), set()
        for i, cand in enumerate(candidates):
            if len(picked) >= count:
                break
            new = cand["_new_chars"] - spent
            if len(new) <= budget:
                picked.append(cand)
                chosen.add(i)
                budget -= len(new)
                spent |= new

        if len(picked) < count:
            for i, cand in enumerate(candidates):
                if len(picked) >= count:
                    break
                if i not in chosen:
                    picked.append(cand)
        return picked

    @staticmethod
    def _strip_ranking_keys(sentences: list) -> list:
        """Drops the private `_`-prefixed ranking fields before returning."""
        return [{k: v for k, v in s.items() if not k.startswith("_")}
                for s in sentences]

    @staticmethod
    def _beginner_batch_size(unlocked: dict, never_graded: set, budget: int) -> int:
        """
        How many characters a character-only batch should hold: the whole
        unlocked pool, less any never-graded characters the day's intake
        budget cannot admit yet, capped at CHARACTER_ONLY_BATCH_CAP.

        This deliberately mirrors what _fill_batch will actually yield --
        every already-graded character costs nothing and always fits, and
        never-graded ones fit while the budget lasts -- so the two agree by
        construction. beginner_bank_is_stale compares a saved bank against
        this same number, and would rewrite that bank on every request if it
        expected a batch larger than _fill_batch can produce.

        Floored at 1 rather than 0 so that an account whose daily_new_limit
        is 0 still gets something to practise: _fill_batch tops a short batch
        up past the budget, and one character is the difference between a
        paced session and finding 18's empty one.
        """
        affordable = len(unlocked) - len(never_graded) + min(budget, len(never_graded))
        return max(1, min(CHARACTER_ONLY_BATCH_CAP, affordable))

    def beginner_bank_is_stale(self, brain_data: dict) -> bool:
        """
        True when a saved character-only bank holds fewer characters than a
        fresh one would, so /api/session should rebuild it rather than serve
        it (see server.py's bootstrap).

        The saved bank is normally replaced only on an explicit "Get
        Sentences", and that stays true for sentences. But character practice
        has no equivalent of finishing a session: the bank is just a window
        onto the unlocked pool, and a window narrower than the pool leaves
        characters permanently unreachable while the "Due" badge still counts
        them. That is what stranded Tier 1 accounts created before the batch
        covered the pool, and it is also what would happen to anyone who
        unlocks a character mid-phase through Suggest Characters or Paste
        Text -- the new character would be due immediately and never served.

        Only ever second-guesses a bank that is entirely single characters,
        so a real sentence bank is never rebuilt behind the learner's back.

        Stable by construction: it asks for exactly the size
        _beginner_batch_size promises, so one rebuild satisfies it and the
        next request leaves the bank alone. A bank held short by the daily
        intake budget is *not* stale -- that is the cap doing its job, and
        treating it as stale would rewrite brain.json on every page load.
        """
        bank = brain_data.get("sentences") or []
        if not bank or any(len(s.get("chinese") or "") != 1 for s in bank):
            return False

        unlocked = brain_data.get("unlocked_chars") or {}
        never_graded, budget = self._new_character_budget(
            unlocked, brain_data, date.today().isoformat())
        return len(bank) < self._beginner_batch_size(unlocked, never_graded, budget)

    @staticmethod
    def _character_candidate(char: str, meta: dict, due_set: set,
                             completed: dict, today_iso: str,
                             never_graded: set, budget: int) -> dict:
        """
        One unlocked character dressed as a one-character "sentence", ranked
        by the same keys real sentences are.

        Shared by the two places that serve individual characters: the
        beginner phase (_pick_beginner_characters) and the stranded-character
        slot a sentence batch reserves (see pick_hsk_sentences). They want
        the same thing -- a character the learner can actually be given --
        and having built the dict in one place, a later change to the ranking
        keys cannot reach one call site and miss the other.
        """
        return {
            "english": meta.get("meaning", ""),
            "chinese": char,
            "kind": "character",
            "_fresh": _freshness(char, completed, today_iso),
            "_due_ratio": _due_ratio(char, due_set),
            "_personal": False,
            "_new_chars": {char} if char in never_graded else set(),
            "_fits": (char not in never_graded) or budget >= 1,
        }

    @staticmethod
    def _word_candidate(word: str, meta: dict, due_set: set,
                        completed: dict, today_iso: str,
                        never_graded: set, budget: int) -> dict:
        """
        One unlocked word dressed as a "sentence" item, the word-side mirror
        of _character_candidate -- the canvas writes a word's characters in
        sequence exactly like a sentence's, so the same item shape works
        unchanged; only `kind` differs, which the frontend uses to grade the
        item via review_word (its own SM-2 schedule) rather than treating it
        as a completed sentence.
        """
        return {
            "english": meta.get("meaning", ""),
            "chinese": word,
            "kind": "word",
            "_fresh": _freshness(word, completed, today_iso),
            "_due_ratio": _due_ratio(word, due_set),
            "_personal": False,
            "_new_chars": {word} if word in never_graded else set(),
            "_fits": (word not in never_graded) or budget >= 1,
        }

    def pick_character_practice(self, count: int = 5) -> list:
        """
        A due-biased batch of standalone single-character practice items,
        used when "characters" is one of the enabled study styles (see
        study_styles) -- so character review is available on its own,
        beyond the sentence pipeline's stranded-character safety net and
        the Tier 1 bootstrap phase, both of which exist independently of
        this setting and are untouched by it.

        Reuses _character_candidate/_fill_batch, the same as
        _pick_beginner_characters, but sized to `count` rather than
        _beginner_batch_size -- Tier 1's "cover the whole pool at once"
        sizing is a bootstrap concern for a pool with no other practice
        option; an ongoing review batch from a large pool wants a normal
        batch size instead.
        """
        brain_data = self._read_brain()
        unlocked = brain_data.get("unlocked_chars", {}) or {}
        if not unlocked:
            return []
        due_set = self.get_due_characters(unlocked)
        completed = brain_data.get("completed_sentences", {}) or {}
        today_iso = date.today().isoformat()
        never_graded, budget = self._new_character_budget(unlocked, brain_data, today_iso)

        candidates = [
            self._character_candidate(char, meta, due_set, completed,
                                      today_iso, never_graded, budget)
            for char, meta in unlocked.items()]
        random.shuffle(candidates)
        candidates.sort(key=lambda c: (c["_fresh"], c["_due_ratio"]), reverse=True)
        return self._strip_ranking_keys(self._fill_batch(candidates, count, budget))

    def pick_word_practice(self, count: int = 5) -> list:
        """
        A due-biased batch of standalone word practice items, used when
        "words" is one of the enabled study styles. Structurally identical
        to pick_character_practice, over unlocked_words and get_due_words
        instead -- words have carried their own independent SM-2 schedule
        since Sept 1, 2026 (see review_word), so they're ranked and paced
        exactly like characters are, just against a separate due set and a
        separate daily intake budget.
        """
        brain_data = self._read_brain()
        unlocked_words = brain_data.get("unlocked_words", {}) or {}
        unlocked_words = {w: m for w, m in unlocked_words.items() if len(w) >= 2}
        if not unlocked_words:
            return []
        due_set = self.get_due_words(unlocked_words)
        completed = brain_data.get("completed_sentences", {}) or {}
        today_iso = date.today().isoformat()
        never_graded, budget = self._new_word_budget(unlocked_words, brain_data, today_iso)

        candidates = [
            self._word_candidate(word, meta, due_set, completed,
                                 today_iso, never_graded, budget)
            for word, meta in unlocked_words.items()]
        random.shuffle(candidates)
        candidates.sort(key=lambda c: (c["_fresh"], c["_due_ratio"]), reverse=True)
        return self._strip_ranking_keys(self._fill_batch(candidates, count, budget))

    def _pick_beginner_characters(self, unlocked: dict, due_set: set,
                                   completed: dict, today_iso: str,
                                   count: int, never_graded: set,
                                   budget: int) -> list:
        """
        Character-only practice: each unlocked character served as its own
        one-character "sentence", English meaning as the prompt. Reuses the
        exact sentence shape pick_hsk_sentences returns (chinese/english),
        so everything downstream -- attach_char_data, the assembly-line
        canvas, SM-2 review, completed_sentences tracking -- works unchanged;
        a "sentence" here is just a chinese string of length one.

        Ranked the same way as real sentences: never-completed characters
        first, then due-for-review ones, so this phase still reinforces SM-2
        scheduling rather than cycling the pool in a fixed order. The daily
        new-character budget applies here too (finding 17) -- a learner
        holding nineteen never-practiced characters should meet them over
        days rather than all at once, exactly as in sentence mode.

        `count` -- the caller's sentence-batch size -- is deliberately
        ignored in favour of _beginner_batch_size. A batch of 3 is right for
        sentences and wrong for characters: it made a 5-character Tier 1 pool
        loop three characters forever while the other two sat in the "Due"
        badge, unreachable. See CHARACTER_ONLY_BATCH_CAP.
        """
        candidates = [
            self._character_candidate(char, meta, due_set, completed,
                                      today_iso, never_graded, budget)
            for char, meta in unlocked.items()]

        random.shuffle(candidates)
        candidates.sort(key=lambda c: (c["_fresh"], c["_due_ratio"]), reverse=True)
        size = self._beginner_batch_size(unlocked, never_graded, budget)
        return self._strip_ranking_keys(self._fill_batch(candidates, size, budget))

    def _stranded_character_picks(self, unlocked: dict, sentences: list,
                                  due_set: set, completed: dict,
                                  today_iso: str, never_graded: set,
                                  budget: int) -> list:
        """
        The unlocked characters that no playable sentence contains, offered as
        one-character items so they are reachable at all -- at most
        STRANDED_CHARACTER_SLOTS of them per batch.

        Sentence practice serves a character only as part of a sentence the
        learner can already write end to end. A character can be unlocked, due
        for review, and counted in the "Due: N" badge while every corpus
        sentence containing it also needs some character the learner does not
        have yet. Nothing then ever serves it: the badge and the practice
        material are computed from different places, which is exactly the
        shape of finding 24, one level up.

        This is not hypothetical and it is not rare at the boundary. Measured
        on the guided path out of Tier 1 -- seed at "First Peel", then take
        Suggest Characters' top pick repeatedly -- crossing
        CHARACTER_ONLY_UNLOCK_THRESHOLD hands the learner 23 playable
        sentences that between them contain only 16 of their 20 characters.
        The other four are 一, 了, 力 and 十: two of the most frequent
        characters in the language, and two of Tier 1's own five. Verified by
        generating 900 sentences against that pool, in which all four appear
        zero times while all four sit in the due set.

        No choice of threshold fixes this, which is why the tuning question
        finding 18 raised has no numeric answer. Lowering it strands a
        *larger* share of a smaller pool (at twelve characters, four of the
        twelve); raising it withholds sentences the learner could be
        practising; and the crossover never arrives -- 力 and 十 are still
        uncovered at 120 characters. The two populations, playable sentences
        and characters those sentences reach, simply grow at different rates,
        and the transition between the two modes was written as though they
        did not.

        Capped at one per batch rather than ranked freely among the sentences.
        A stranded character that is due scores 1.0 on _due_ratio, the
        maximum any item can score, so uncapped they would take the whole
        batch and turn a sentence session into character drill -- which is a
        real risk for a large pool carrying rare pasted characters, not just
        at the boundary. One slot is enough to make every stranded character
        reachable within a few batches while the session stays sentence-shaped.
        """
        covered = set()
        for cand in sentences:
            covered.update(cand["chinese"])
        stranded = [char for char in unlocked if char not in covered]
        if not stranded:
            return []

        picks = [self._character_candidate(char, unlocked[char], due_set,
                                           completed, today_iso, never_graded,
                                           budget)
                 for char in stranded]
        random.shuffle(picks)
        picks.sort(key=lambda c: (c["_fresh"], c["_due_ratio"]), reverse=True)
        return picks[:STRANDED_CHARACTER_SLOTS]

    def pick_hsk_sentences(self, count: int = 5) -> list:
        """
        Picks real example sentences -- from the hand-curated HSK corpora, the
        larger Tatoeba-derived corpus, and the user's own saved pasted
        sentences -- whose characters are entirely within the user's currently
        unlocked pool. No AI, no network call, no API key required. The
        user's own pasted sentences are always ranked ahead of corpus
        sentences (real content they chose to study takes priority over
        anything the offline corpus happens to contain); within each of
        those two groups, sentences that reuse characters currently due for
        SM-2 review are preferred over ones that don't, so practice
        naturally reinforces what's due.

        That preference is measured as a *proportion* of the sentence, not a
        raw count of due characters. Counting hits made length the dominant
        term by accident: a 12-character sentence mentioning four due
        characters outranked a 4-character sentence made entirely of them,
        because 4 > 1. With a due queue of any real size almost every
        sentence contains several due characters, so ranking by count
        degenerated into "always serve the longest sentence available" --
        measured on a 111-character pool, picks averaged 10.3 characters
        against a 6.0 average for the sentences actually available, and every
        pick sat at or near the 12-character maximum. That is exactly
        backwards for a beginner, who has the smallest unlocked pool and the
        least business being handed the longest sentences in it.

        How many characters the learner has never met is a fourth term, above
        freshness (finding 17). Freshness alone pulls hard toward unseen
        sentences, which is right for variety and wrong for pacing: an unseen
        sentence tends to be unseen partly *because* it contains characters
        the learner has never been given, so preferring it silently
        introduced far more new characters per session than
        settings.daily_new_limit claims. `_fits` asks whether a sentence's
        never-graded characters still fit today's remaining allowance, and
        _fill_batch spends that allowance across the batch as a whole.

        Practice falls back to individual characters -- see
        _pick_beginner_characters -- in two cases. The cheap one is a pool
        below CHARACTER_ONLY_UNLOCK_THRESHOLD, which is Tier 1's deliberate
        beginner phase (seed_brain.py picks those characters for simplicity,
        not sentence coverage, so zero sentences are playable on purpose).
        The other is any pool, of any size, that yields no playable sentence
        at all. That second case is finding 18: the threshold is a character
        count standing in for "are sentences available yet?", and the two
        come apart -- twenty characters that happen to complete no sentence
        left the learner with an empty session, having had working character
        practice at nineteen. Falling back on the actual corpus result rather
        than on the count closes the gap in both directions.
        """
        brain_data = self._read_brain()
        unlocked_chars = brain_data.get("unlocked_chars", {})
        if not unlocked_chars:
            return []

        due_set = self.get_due_characters(unlocked_chars)
        completed = brain_data.get("completed_sentences", {}) or {}
        today_iso = date.today().isoformat()
        never_graded, budget = self._new_character_budget(
            unlocked_chars, brain_data, today_iso)

        def beginner_batch():
            return self._pick_beginner_characters(
                unlocked_chars, due_set, completed, today_iso, count,
                never_graded, budget)

        if len(unlocked_chars) < CHARACTER_ONLY_UNLOCK_THRESHOLD:
            return beginner_batch()

        unlocked_set = set(unlocked_chars)
        allowed_punct = "，。！？、；：“”‘’—…"
        candidates = []
        seen_chinese = set()

        def add_candidate(chinese, english, personal):
            seen_chinese.add(chinese)
            new_chars = {c for c in chinese if c in never_graded}
            candidates.append({
                "english": english, "chinese": chinese,
                "kind": "sentence",
                "_fresh": _freshness(chinese, completed, today_iso),
                "_due_ratio": _due_ratio(chinese, due_set),
                "_personal": personal,
                "_new_chars": new_chars,
                "_fits": len(new_chars) <= budget,
            })

        for item in brain_data.get("pasted_sentences", []) or []:
            chinese = (item.get("chinese") or "").strip()
            english = (item.get("english") or "").strip()
            if not chinese or not english or chinese in seen_chinese:
                continue
            if all(c in unlocked_set or c in allowed_punct for c in chinese):
                add_candidate(chinese, english, True)

        for filename in SENTENCE_SOURCE_FILES:
            if not os.path.exists(filename):
                continue
            try:
                with open(filename, "r", encoding="utf-8") as f:
                    reader = csv.DictReader(f, delimiter="\t")
                    for row in reader:
                        chinese = (row.get("sentence") or "").replace(" ", "").strip()
                        english = (row.get("sentence_meaning") or "").strip()
                        if not chinese or not english or chinese in seen_chinese:
                            continue
                        if all(c in unlocked_set or c in allowed_punct for c in chinese):
                            add_candidate(chinese, english, False)
            except Exception as e:
                print(f"Warning: could not read {filename}: {e}")

        # Finding 18: a pool past the threshold that still closes over no
        # sentence gets character practice rather than nothing.
        if not candidates:
            return beginner_batch()

        candidates.extend(self._stranded_character_picks(
            unlocked_chars, candidates, due_set, completed, today_iso,
            never_graded, budget))

        # Shuffle first so that sentences tying on the sort key come back in a
        # different order each time rather than in corpus order.
        random.shuffle(candidates)
        candidates.sort(
            key=lambda c: (c["_personal"], c["_fits"], c["_fresh"], c["_due_ratio"]),
            reverse=True)
        return self._strip_ranking_keys(self._fill_batch(candidates, count, budget))

    def generate_fresh_session(self, count: int = 5, styles: set = None) -> dict:
        """
        Picks a brand new practice batch -- real example sentences from the
        local HSK/Tatoeba corpora and the user's own saved pasted sentences,
        standalone characters, and/or standalone words, depending on which
        study styles are currently enabled (see study_styles) -- and
        replaces the saved queue in brain.json, so a completed session
        doesn't just replay the same material forever. No AI, no network, no
        key needed. If no items come back, the existing saved bank is left
        untouched.

        `styles`, if given, overrides the account's own study_styles setting
        for this one call -- used by the Import modal's "HSK Sentences" tab,
        whose "Get Sentences" button is an explicit request for sentences
        specifically and shouldn't start handing back word/character items
        just because the learner has narrowed their general study styles.
        The page-load bootstrap (see server.py's /api/session) calls this
        with no override, so it's the one place the toggle actually governs.

        Each enabled style contributes its own sub-batch (via
        pick_hsk_sentences/pick_character_practice/pick_word_practice)
        rather than being merged into one shared candidate pool: they rank
        against genuinely different due sets and different daily-intake
        budgets (a due character and a due word are not the same kind of
        "due"), and pick_hsk_sentences' own internal ranking is already
        carefully tuned (freshness/due-ratio/personal/new-chars-budget) --
        folding a second currency (new *words*) into that would risk
        breaking it in ways worth avoiding for what a Settings toggle needs.
        `count` is split evenly across whichever styles are enabled, with a
        floor of 1 each, so turning on all three doesn't triple the batch
        size.
        """
        with self.brain_lock:
            brain_data = {"unlocked_chars": {}, "sentences": []}
            if os.path.exists(self.brain_path):
                try:
                    with open(self.brain_path, "r", encoding="utf-8") as f:
                        brain_data = json.load(f)
                except Exception as e:
                    print(f"Error reading brain database: {e}")
            unlocked_chars = brain_data.get("unlocked_chars", {})
            if styles is None:
                styles = self.study_styles(brain_data)

            # These reacquire brain_lock through their own helpers, which is
            # safe since it's an RLock, and are fast local reads with no
            # network call, so holding the lock across them doesn't stall
            # other requests.
            per_style_count = max(1, -(-count // max(1, len(styles))))  # ceil division
            raw_items = []
            if "sentences" in styles:
                raw_items += self.pick_hsk_sentences(count=per_style_count)
            if "characters" in styles:
                raw_items += self.pick_character_practice(count=per_style_count)
            if "words" in styles:
                raw_items += self.pick_word_practice(count=per_style_count)
            random.shuffle(raw_items)

            master_dict = self.load_master_dictionary()
            new_sentences = []
            for item in raw_items:
                sentence = {"english": item["english"], "chinese": item["chinese"],
                           "kind": item.get("kind", "sentence")}
                self.attach_char_data(sentence, unlocked_chars, master_dict)
                new_sentences.append(sentence)

            if new_sentences:
                brain_data["sentences"] = new_sentences
                with open(self.brain_path, "w", encoding="utf-8") as f:
                    json.dump(brain_data, f, ensure_ascii=False, indent=4)

            return {
                "sentences": brain_data.get("sentences", []),
                "total_unlocked_count": len(unlocked_chars),
                # Returned so the "Due: N" badge can refresh with the new
                # batch. Without it the frontend had no due figure to apply
                # and left the badge showing whatever it read at page load,
                # which drifts further from the truth with every review.
                "total_due_count": self.total_due_count(brain_data),
            }

